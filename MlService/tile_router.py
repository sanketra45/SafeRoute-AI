"""
SafeRoute AI — Tile-Based Lazy Graph Router
============================================
Splits the Nagpur road network into overlapping geographic tiles.
Tiles are loaded on demand (lazy) and evicted via LRU when memory
pressure builds up.

Architecture:
  - Nagpur bbox split into N×M tiles with OVERLAP_DEG margin.
  - Each tile is a sub-graphml file in MlService/data/tiles/.
  - TileCache keeps at most MAX_TILES loaded simultaneously.
  - Routing stitches tiles covering origin→destination corridor.
  - If tiles are missing, falls back to direct OSMnx download.

Tile files are pre-generated by: python generate_tiles.py
"""

import os
import math
import time
import heapq
import logging
import threading
import warnings
from collections import OrderedDict
from typing import Optional, Dict, Tuple, List

import numpy as np
import pandas as pd
import networkx as nx

warnings.filterwarnings("ignore", category=FutureWarning)
log = logging.getLogger(__name__)

# ── Paths ────────────────────────────────────────────────────────
BASE_DIR      = os.path.dirname(os.path.abspath(__file__))
TILES_DIR     = os.path.join(BASE_DIR, "data", "tiles")
DATASET_PATH  = os.path.join(BASE_DIR, "nagpur_accident_dataset.csv")

# ── Nagpur Bounding Box ──────────────────────────────────────────
# Roughly covers the full Nagpur metropolitan area
NAGPUR_BBOX = {
    "lat_min": 20.85,
    "lat_max": 21.45,
    "lon_min": 78.85,
    "lon_max": 79.35,
}

# ── Tile Grid Config ─────────────────────────────────────────────
GRID_ROWS    = 4          # 4 rows × 4 cols = 16 tiles
GRID_COLS    = 4
OVERLAP_DEG  = 0.025      # ~2.5 km overlap on each border to ensure connectivity
MAX_TILES    = 6          # Maximum tiles kept in RAM simultaneously
RISK_PENALTY = 500

# ── Road Risk Tables (identical to risk_router.py) ───────────────
HIGHWAY_RISK = {
    "motorway": 0.85, "motorway_link": 0.80,
    "trunk": 0.75,    "trunk_link": 0.70,
    "primary": 0.55,  "primary_link": 0.50,
    "secondary": 0.45,"secondary_link": 0.40,
    "tertiary": 0.35, "tertiary_link": 0.30,
    "unclassified": 0.30, "residential": 0.20,
    "living_street": 0.10, "service": 0.15,
    "track": 0.40,    "path": 0.35,
}
DEFAULT_HIGHWAY_RISK = 0.35

SURFACE_RISK = {
    "asphalt": 0.10, "paved": 0.10, "concrete": 0.12,
    "paving_stones": 0.20, "sett": 0.25, "cobblestone": 0.30,
    "compacted": 0.35, "fine_gravel": 0.45, "gravel": 0.55,
    "unpaved": 0.65, "dirt": 0.70, "grass": 0.75, "sand": 0.80,
}
DEFAULT_SURFACE_RISK = 0.30

JUNCTION_RISK = {"roundabout": 0.35, "circular": 0.35, "yes": 0.50}
DEFAULT_JUNCTION_RISK = 0.10

WEATHER_RISK = {
    "THUNDERSTORM": 0.90, "RAIN": 0.65, "DRIZZLE": 0.45,
    "SNOW": 0.60, "FOG": 0.70, "MIST": 0.40, "HAZE": 0.35,
    "SMOKE": 0.45, "DUST": 0.45, "SAND": 0.50, "CLOUDS": 0.15,
    "CLOUDY": 0.15, "CLEAR": 0.0,
}

BLACKSPOT_RADIUS_M = 250


# ── Helpers ──────────────────────────────────────────────────────

def _haversine_m(lat1, lng1, lat2, lng2):
    R = 6_371_000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lng2 - lng1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R * math.asin(math.sqrt(max(0.0, a)))


def _speed_risk(speed_str) -> float:
    try:
        val = float(str(speed_str).split()[0])
    except (ValueError, TypeError):
        return 0.35
    return min(val / 120.0, 1.0)


def _load_blackspot_tree(csv_path):
    """Load accident blackspot records + optional spatial index."""
    if not os.path.exists(csv_path):
        log.warning("Accident dataset not found at %s", csv_path)
        return None, []
    df = pd.read_csv(csv_path)
    severity_map = {"Low": 0.5, "Medium": 0.75, "High": 1.0}
    records = []
    for _, row in df.iterrows():
        try:
            lat   = float(row["latitude"])
            lng   = float(row["longitude"])
            sev   = severity_map.get(str(row.get("risk_level", "Medium")).strip(), 0.75)
            count = min(float(row.get("accident_count", 1)) / 10.0, 1.0)
            score = min(sev * (0.5 + 0.5 * count), 1.0)
            records.append((lat, lng, score))
        except (ValueError, TypeError):
            continue
    try:
        from scipy.spatial import cKDTree
        tree = cKDTree(np.array([(lat, lng) for lat, lng, _ in records])) if records else None
    except ImportError:
        tree = None
    log.info("Loaded %d blackspot records%s", len(records),
             " with spatial index" if tree else "")
    return tree, records


def _node_blackspot_score(nlat, nlng, blackspots, radius_m=BLACKSPOT_RADIUS_M):
    best = 0.0
    tree, records = blackspots if isinstance(blackspots, tuple) else (None, blackspots)
    if tree is not None:
        candidates = tree.query_ball_point([nlat, nlng], radius_m / 100_000.0)
    else:
        candidates = range(len(records))
    for idx in candidates:
        blat, blng, bscore = records[idx]
        d = _haversine_m(nlat, nlng, blat, blng)
        if d <= radius_m:
            best = max(best, bscore * (1.0 - d / radius_m))
    return best


def _edge_risk_score(edge_data, u_lat, u_lng, v_lat, v_lng, blackspots):
    hw = edge_data.get("highway", "")
    if isinstance(hw, list): hw = hw[0] if hw else ""
    hw_risk    = HIGHWAY_RISK.get(str(hw).strip(), DEFAULT_HIGHWAY_RISK)
    speed_risk = _speed_risk(edge_data.get("maxspeed"))
    lit        = str(edge_data.get("lit", "")).strip().lower()
    light_risk = 0.10 if lit == "yes" else (0.70 if lit in ("no", "") else 0.40)
    surf_risk  = SURFACE_RISK.get(str(edge_data.get("surface", "")).strip().lower(), DEFAULT_SURFACE_RISK)
    junc_risk  = JUNCTION_RISK.get(str(edge_data.get("junction", "")).strip().lower(), DEFAULT_JUNCTION_RISK)
    mid_lat    = (u_lat + v_lat) / 2.0
    mid_lng    = (u_lng + v_lng) / 2.0
    acc_risk   = _node_blackspot_score(mid_lat, mid_lng, blackspots)
    risk = (0.20 * hw_risk + 0.20 * speed_risk + 0.15 * light_risk +
            0.15 * surf_risk + 0.10 * junc_risk + 0.20 * acc_risk)
    return float(np.clip(risk, 0.0, 1.0))


def _annotate_edges(G, blackspots):
    """Annotate graph edges with risk_score and safe_weight."""
    node_data = dict(G.nodes(data=True))
    for u, v, key, data in G.edges(keys=True, data=True):
        u_info = node_data.get(u, {})
        v_info = node_data.get(v, {})
        u_lat  = float(u_info.get("y", 0))
        u_lng  = float(u_info.get("x", 0))
        v_lat  = float(v_info.get("y", 0))
        v_lng  = float(v_info.get("x", 0))
        length = float(data.get("length", 50.0))
        risk   = _edge_risk_score(data, u_lat, u_lng, v_lat, v_lng, blackspots)
        G[u][v][key]["risk_score"]  = risk
        G[u][v][key]["safe_weight"] = length + (risk * RISK_PENALTY)


# ── Tile Index ───────────────────────────────────────────────────

def get_tile_id(row: int, col: int) -> str:
    return f"tile_{row:02d}_{col:02d}"


def tile_bbox(row: int, col: int) -> Dict:
    """Return (lat_min, lat_max, lon_min, lon_max) for tile (row, col) WITHOUT overlap."""
    lat_total = NAGPUR_BBOX["lat_max"] - NAGPUR_BBOX["lat_min"]
    lon_total = NAGPUR_BBOX["lon_max"] - NAGPUR_BBOX["lon_min"]
    lat_step  = lat_total / GRID_ROWS
    lon_step  = lon_total / GRID_COLS
    return {
        "lat_min": NAGPUR_BBOX["lat_min"] + row * lat_step,
        "lat_max": NAGPUR_BBOX["lat_min"] + (row + 1) * lat_step,
        "lon_min": NAGPUR_BBOX["lon_min"] + col * lon_step,
        "lon_max": NAGPUR_BBOX["lon_min"] + (col + 1) * lon_step,
    }


def tile_bbox_with_overlap(row: int, col: int) -> Dict:
    """Return bbox expanded by OVERLAP_DEG on each side (for tile download)."""
    bb = tile_bbox(row, col)
    return {
        "lat_min": max(NAGPUR_BBOX["lat_min"] - 0.01, bb["lat_min"] - OVERLAP_DEG),
        "lat_max": min(NAGPUR_BBOX["lat_max"] + 0.01, bb["lat_max"] + OVERLAP_DEG),
        "lon_min": max(NAGPUR_BBOX["lon_min"] - 0.01, bb["lon_min"] - OVERLAP_DEG),
        "lon_max": min(NAGPUR_BBOX["lon_max"] + 0.01, bb["lon_max"] + OVERLAP_DEG),
    }


def coord_to_tile(lat: float, lng: float) -> Tuple[int, int]:
    """Map a lat/lng to tile (row, col). Clamps to valid grid."""
    lat_total = NAGPUR_BBOX["lat_max"] - NAGPUR_BBOX["lat_min"]
    lon_total = NAGPUR_BBOX["lon_max"] - NAGPUR_BBOX["lon_min"]
    lat_step  = lat_total / GRID_ROWS
    lon_step  = lon_total / GRID_COLS
    row = int((lat - NAGPUR_BBOX["lat_min"]) / lat_step)
    col = int((lng - NAGPUR_BBOX["lon_min"]) / lon_step)
    row = max(0, min(GRID_ROWS - 1, row))
    col = max(0, min(GRID_COLS - 1, col))
    return row, col


def tiles_for_corridor(lat1, lng1, lat2, lng2) -> List[Tuple[int, int]]:
    """
    Return all tile indices needed to route from (lat1,lng1) to (lat2,lng2).
    Samples points along the straight-line corridor and adds a 1-tile border buffer.
    """
    needed = set()
    SAMPLES = 12
    for i in range(SAMPLES + 1):
        t   = i / SAMPLES
        lat = lat1 + t * (lat2 - lat1)
        lng = lng1 + t * (lng2 - lng1)
        row, col = coord_to_tile(lat, lng)
        # Add the tile and all immediate neighbours (buffer)
        for dr in (-1, 0, 1):
            for dc in (-1, 0, 1):
                r2 = row + dr
                c2 = col + dc
                if 0 <= r2 < GRID_ROWS and 0 <= c2 < GRID_COLS:
                    needed.add((r2, c2))
    return sorted(needed)


def tile_graphml_path(row: int, col: int) -> str:
    return os.path.join(TILES_DIR, f"{get_tile_id(row, col)}.graphml")


def tiles_available() -> bool:
    """Check if at least some tile files exist."""
    if not os.path.isdir(TILES_DIR):
        return False
    for row in range(GRID_ROWS):
        for col in range(GRID_COLS):
            if os.path.exists(tile_graphml_path(row, col)):
                return True
    return False


# ── LRU Tile Cache ───────────────────────────────────────────────

class TileCache:
    """
    Thread-safe LRU cache for road network graph tiles.
    Holds at most MAX_TILES annotated NetworkX graphs.
    """

    def __init__(self, max_tiles: int = MAX_TILES):
        self._max   = max_tiles
        self._cache: OrderedDict[str, nx.MultiDiGraph] = OrderedDict()
        self._lock  = threading.Lock()
        self._blackspots = None   # shared across all tiles

    def _ensure_blackspots(self):
        if self._blackspots is None:
            self._blackspots = _load_blackspot_tree(DATASET_PATH)
        return self._blackspots

    def _load_tile(self, row: int, col: int) -> Optional[nx.MultiDiGraph]:
        path = tile_graphml_path(row, col)
        if not os.path.exists(path):
            log.warning("[TILE] File missing: %s", path)
            return None
        t0 = time.time()
        try:
            import osmnx as ox
            G = ox.load_graphml(path)
            G = nx.MultiDiGraph(G)
        except ImportError:
            G = nx.read_graphml(path)
        bs = self._ensure_blackspots()
        _annotate_edges(G, bs)
        log.info("[TILE] Loaded tile_%02d_%02d  nodes=%d  edges=%d  t=%.1fs",
                 row, col, G.number_of_nodes(), G.number_of_edges(), time.time() - t0)
        return G

    def get(self, row: int, col: int) -> Optional[nx.MultiDiGraph]:
        key = get_tile_id(row, col)
        with self._lock:
            if key in self._cache:
                self._cache.move_to_end(key)  # mark as recently used
                return self._cache[key]
        # Load outside the lock to avoid blocking other threads
        G = self._load_tile(row, col)
        if G is None:
            return None
        with self._lock:
            if key not in self._cache:  # another thread may have loaded it
                self._cache[key] = G
                self._cache.move_to_end(key)
                # Evict LRU tiles over limit
                while len(self._cache) > self._max:
                    evicted_key, _ = self._cache.popitem(last=False)
                    log.info("[TILE] Evicted %s from cache (LRU)", evicted_key)
            else:
                self._cache.move_to_end(key)
        return self._cache.get(key)

    def get_tiles_for_route(self, lat1, lng1, lat2, lng2) -> Optional[nx.MultiDiGraph]:
        """
        Load and compose all tiles needed for this route into a single graph.
        Returns None if no tiles are available for the area.
        """
        tile_ids = tiles_for_corridor(lat1, lng1, lat2, lng2)
        log.info("[TILE] Route corridor needs tiles: %s",
                 [get_tile_id(r, c) for r, c in tile_ids])

        graphs = []
        for row, col in tile_ids:
            G = self.get(row, col)
            if G is not None:
                graphs.append(G)

        if not graphs:
            log.error("[TILE] No tiles could be loaded for this route corridor.")
            return None

        if len(graphs) == 1:
            return graphs[0]

        # Compose tiles into a single graph (shared node IDs from OSM ensure connectivity)
        t0 = time.time()
        combined = nx.compose_all(graphs)
        log.info("[TILE] Composed %d tiles → %d nodes %d edges  t=%.2fs",
                 len(graphs), combined.number_of_nodes(), combined.number_of_edges(),
                 time.time() - t0)
        return combined

    def cache_info(self):
        with self._lock:
            return {k: {"nodes": G.number_of_nodes(), "edges": G.number_of_edges()}
                    for k, G in self._cache.items()}


# Singleton cache instance
_tile_cache: Optional[TileCache] = None
_cache_lock = threading.Lock()


def get_tile_cache() -> TileCache:
    global _tile_cache
    if _tile_cache is None:
        with _cache_lock:
            if _tile_cache is None:
                _tile_cache = TileCache(max_tiles=MAX_TILES)
    return _tile_cache


# ── Nearest-Node lookup ──────────────────────────────────────────

def _nearest_node(G, lat, lng):
    try:
        import osmnx as ox
        return ox.nearest_nodes(G, X=lng, Y=lat)
    except (ImportError, KeyError, ValueError, Exception):
        pass
    best_node, best_dist = None, float("inf")
    for node, data in G.nodes(data=True):
        try:
            d = _haversine_m(lat, lng,
                             float(data.get("y", 0)),
                             float(data.get("x", 0)))
            if d < best_dist:
                best_dist, best_node = d, node
        except (ValueError, TypeError):
            continue
    return best_node


# ── A* Heuristic ─────────────────────────────────────────────────

def _astar_heuristic(G):
    node_data = dict(G.nodes(data=True))
    def h(u, target):
        ui = node_data.get(u, {})
        ti = node_data.get(target, {})
        return _haversine_m(float(ui.get("y", 0)), float(ui.get("x", 0)),
                            float(ti.get("y", 0)), float(ti.get("x", 0)))
    return h


# ── Live Conditions ──────────────────────────────────────────────

def _live_conditions(conditions):
    conditions = conditions or {}
    traffic = conditions.get("traffic") or {}
    weather = conditions.get("weather") or {}
    try:
        current_speed = float(traffic.get("currentSpeed", 0))
        free_speed    = float(traffic.get("freeFlowSpeed", 0))
    except (TypeError, ValueError):
        current_speed = free_speed = 0.0
    congestion    = (max(0.0, min(1.0, 1.0 - current_speed / free_speed))
                     if free_speed > 0 and current_speed > 0 else 0.0)
    condition     = str(weather.get("condition") or weather.get("weather") or "CLEAR").upper()
    weather_risk  = WEATHER_RISK.get(condition, 0.20)
    return congestion, weather_risk


# ── Route Computation ────────────────────────────────────────────

def _compute_route(G, origin_lat, origin_lng, dest_lat, dest_lng,
                   risk_penalty=RISK_PENALTY, live_conditions=None):
    """Core A* routing on a composed graph G."""
    try:
        origin_node = _nearest_node(G, origin_lat, origin_lng)
        dest_node   = _nearest_node(G, dest_lat, dest_lng)
        if origin_node is None or dest_node is None:
            return {"success": False, "error": "Could not snap coordinates to graph nodes."}
        if origin_node == dest_node:
            return {"success": False, "error": "Origin and destination snap to the same node."}

        heuristic            = _astar_heuristic(G)
        congestion, wx_risk  = _live_conditions(live_conditions)

        def weight_fn(u, v, edge_dict):
            min_w = float("inf")
            for key, data in edge_dict.items():
                length    = float(data.get("length", 50.0))
                base_risk = float(data.get("risk_score", 0.35))
                dyn_risk  = min(1.0, base_risk + 0.25 * wx_risk + 0.20 * congestion)
                w         = length * (1.0 + 1.5 * congestion) + dyn_risk * risk_penalty
                min_w     = min(min_w, w)
            return min_w

        path_nodes = nx.astar_path(G, source=origin_node, target=dest_node,
                                   heuristic=heuristic, weight=weight_fn)

        node_data    = dict(G.nodes(data=True))
        route_coords = []
        for n in path_nodes:
            nd = node_data.get(n, {})
            route_coords.append([round(float(nd.get("y", 0)), 6),
                                  round(float(nd.get("x", 0)), 6)])

        total_dist_m, edge_risks = 0.0, []
        for i in range(len(path_nodes) - 1):
            u, v = path_nodes[i], path_nodes[i + 1]
            best_data, best_w = None, float("inf")
            for key, data in G[u][v].items():
                length    = float(data.get("length", 50.0))
                base_risk = float(data.get("risk_score", 0.35))
                dyn_risk  = min(1.0, base_risk + 0.25 * wx_risk + 0.20 * congestion)
                w         = length * (1.0 + 1.5 * congestion) + dyn_risk * risk_penalty
                if w < best_w:
                    best_w, best_data = w, data
            if best_data:
                total_dist_m += float(best_data.get("length", 0))
                edge_risks.append(
                    min(1.0, float(best_data.get("risk_score", 0.35)) +
                        0.25 * wx_risk + 0.20 * congestion))

        avg_risk = float(np.mean(edge_risks)) if edge_risks else 0.0
        max_risk = float(np.max(edge_risks))  if edge_risks else 0.0

        return {
            "success":           True,
            "route_nodes":       [str(n) for n in path_nodes],
            "route_coords":      route_coords,
            "total_distance_m":  round(total_dist_m, 1),
            "total_distance_km": round(total_dist_m / 1000.0, 3),
            "avg_risk_score":    round(avg_risk, 4),
            "max_risk_score":    round(max_risk, 4),
            "risk_level":        ("High" if avg_risk >= 0.55 else "Medium" if avg_risk >= 0.25 else "Low"),
            "num_waypoints":     len(path_nodes),
            "origin_node":       str(origin_node),
            "dest_node":         str(dest_node),
            "live_conditions":   {"congestion": round(congestion, 3),
                                  "weather_risk": round(wx_risk, 3)},
        }

    except nx.NetworkXNoPath:
        return {"success": False, "error": "No path found between origin and destination."}
    except nx.NodeNotFound as e:
        return {"success": False, "error": f"Node not found: {e}"}
    except Exception as e:
        log.exception("Tile routing error")
        return {"success": False, "error": str(e)}


def compare_routes_tile(origin_lat, origin_lng, dest_lat, dest_lng,
                        live_conditions=None):
    """
    Public entry point: load required tiles, compute safe and fast routes,
    return comparison dict compatible with the existing /safe-route API.
    """
    cache = get_tile_cache()
    G = cache.get_tiles_for_route(origin_lat, origin_lng, dest_lat, dest_lng)

    if G is None:
        return {
            "safe_route":  {"success": False, "error": "No tile graph available for this area. Run generate_tiles.py."},
            "short_route": {"success": False, "error": "No tile graph available for this area."},
            "comparison":  {},
        }

    safe    = _compute_route(G, origin_lat, origin_lng, dest_lat, dest_lng,
                              risk_penalty=RISK_PENALTY, live_conditions=live_conditions)
    shortest = _compute_route(G, origin_lat, origin_lng, dest_lat, dest_lng,
                               risk_penalty=0, live_conditions=live_conditions)

    comparison = {}
    if safe.get("success") and shortest.get("success"):
        extra_m   = safe["total_distance_m"] - shortest["total_distance_m"]
        risk_cut  = shortest["avg_risk_score"] - safe["avg_risk_score"]
        comparison = {
            "extra_distance_m":   round(extra_m, 1),
            "extra_distance_km":  round(extra_m / 1000.0, 3),
            "risk_reduction":     round(risk_cut, 4),
            "risk_reduction_pct": round(risk_cut * 100, 1),
            "recommendation": (
                "Safe route recommended" if risk_cut > 0.05
                else "Routes are similar — shortest path is fine"
            ),
        }

    return {"safe_route": safe, "short_route": shortest, "comparison": comparison}
