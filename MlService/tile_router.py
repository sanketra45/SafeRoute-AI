BLACKSPOT_RADIUS_M = 250


# ── Helpers ──────────────────────────────────────────────────────

def _haversine_m(lat1, lng1, lat2, lng2):
    R = 6_371_000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lng2 - lng1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R * math.asin(math.sqrt(max(0.0, a)))


def _speed_risk(speed_str) -> float:
    try:
        val = float(str(speed_str).split()[0])
    except (ValueError, TypeError):
        return 0.35
    return min(val / 120.0, 1.0)


def _load_blackspot_tree(csv_path):
    """Load accident blackspot records + optional spatial index."""
    if not os.path.exists(csv_path):
        log.warning("Accident dataset not found at %s", csv_path)
        return None, []
    df = pd.read_csv(csv_path)
    severity_map = {"Low": 0.5, "Medium": 0.75, "High": 1.0}
    records = []
    for _, row in df.iterrows():
        try:
            lat   = float(row["latitude"])
            lng   = float(row["longitude"])
            sev   = severity_map.get(str(row.get("risk_level", "Medium")).strip(), 0.75)
            count = min(float(row.get("accident_count", 1)) / 10.0, 1.0)
            score = min(sev * (0.5 + 0.5 * count), 1.0)
            records.append((lat, lng, score))
        except (ValueError, TypeError):
            continue
    try:
        from scipy.spatial import cKDTree
        tree = cKDTree(np.array([(lat, lng) for lat, lng, _ in records])) if records else None
    except ImportError:
        tree = None
    log.info("Loaded %d blackspot records%s", len(records),
             " with spatial index" if tree else "")
    return tree, records


def _node_blackspot_score(nlat, nlng, blackspots, radius_m=BLACKSPOT_RADIUS_M):
    best = 0.0
    tree, records = blackspots if isinstance(blackspots, tuple) else (None, blackspots)
    if tree is not None:
        candidates = tree.query_ball_point([nlat, nlng], radius_m / 100_000.0)
    else:
        candidates = range(len(records))
    for idx in candidates:
        blat, blng, bscore = records[idx]
        d = _haversine_m(nlat, nlng, blat, blng)
        if d <= radius_m:
            best = max(best, bscore * (1.0 - d / radius_m))
    return best


def _edge_risk_score(edge_data, u_lat, u_lng, v_lat, v_lng, blackspots):
    hw = edge_data.get("highway", "")
    if isinstance(hw, list): hw = hw[0] if hw else ""
    hw_risk    = HIGHWAY_RISK.get(str(hw).strip(), DEFAULT_HIGHWAY_RISK)
    speed_risk = _speed_risk(edge_data.get("maxspeed"))
    lit        = str(edge_data.get("lit", "")).strip().lower()
    light_risk = 0.10 if lit == "yes" else (0.70 if lit in ("no", "") else 0.40)
    surf_risk  = SURFACE_RISK.get(str(edge_data.get("surface", "")).strip().lower(), DEFAULT_SURFACE_RISK)
    junc_risk  = JUNCTION_RISK.get(str(edge_data.get("junction", "")).strip().lower(), DEFAULT_JUNCTION_RISK)
    mid_lat    = (u_lat + v_lat) / 2.0
    mid_lng    = (u_lng + v_lng) / 2.0
    acc_risk   = _node_blackspot_score(mid_lat, mid_lng, blackspots)
    risk = (0.20 * hw_risk + 0.20 * speed_risk + 0.15 * light_risk +
            0.15 * surf_risk + 0.10 * junc_risk + 0.20 * acc_risk)
    return float(np.clip(risk, 0.0, 1.0))


def _annotate_edges(G, blackspots):
    """Keep only route-critical edge attributes after risk annotation."""
    for u, v, key, data in G.edges(keys=True, data=True):
        u_info = G.nodes[u]
        v_info = G.nodes[v]
        u_lat  = float(u_info.get("y", 0))
        u_lng  = float(u_info.get("x", 0))
        v_lat  = float(v_info.get("y", 0))
        v_lng  = float(v_info.get("x", 0))
        length = float(data.get("length", 50.0))
        risk   = _edge_risk_score(data, u_lat, u_lng, v_lat, v_lng, blackspots)
        data.clear()
        data.update(length=length, risk_score=risk)


def _graphml_id(value):
    try:
        return int(value)
    except (TypeError, ValueError):
        return value


def _load_route_graphml(path):
    """Load only node coordinates and edge fields consumed by route scoring."""
    graph = nx.MultiDiGraph()
    key_names = {}
    stack = []
    graph_children = {GRAPHML_TAG + "node", GRAPHML_TAG + "edge", GRAPHML_TAG + "key"}
    edge_fields = {"length", "highway", "maxspeed", "lit", "surface", "junction"}

    for event, elem in ET.iterparse(path, events=("start", "end")):
        if event == "start":
            stack.append(elem)
            continue

        if elem.tag == GRAPHML_TAG + "key":
            key_names[elem.attrib.get("id")] = elem.attrib.get("attr.name")
        elif elem.tag == GRAPHML_TAG + "node":
            attributes = {
                key_names.get(data.attrib.get("key")): data.text
                for data in elem.findall(GRAPHML_TAG + "data")
            }
            try:
                lat = float(attributes["y"])
                lng = float(attributes["x"])
            except (KeyError, TypeError, ValueError) as error:
                raise ValueError(f"Node {elem.attrib.get('id')} has invalid coordinates") from error
            graph.add_node(_graphml_id(elem.attrib["id"]), y=lat, x=lng)
        elif elem.tag == GRAPHML_TAG + "edge":
            attributes = {
                key_names.get(data.attrib.get("key")): data.text
                for data in elem.findall(GRAPHML_TAG + "data")
                if key_names.get(data.attrib.get("key")) in edge_fields
            }
            values = {}
            for name, value in attributes.items():
                if value is None:
                    continue
                if name == "length":
                    try:
                        values[name] = float(value)
                    except (TypeError, ValueError):
                        continue
                elif name == "highway" and value.startswith("["):
                    try:
                        values[name] = ast.literal_eval(value)
                    except (SyntaxError, ValueError):
                        values[name] = value
                else:
                    values[name] = value
            graph.add_edge(
                _graphml_id(elem.attrib["source"]),
                _graphml_id(elem.attrib["target"]),
                key=_graphml_id(elem.attrib["id"]) if "id" in elem.attrib else None,
                **values,
            )

        if elem.tag in graph_children and len(stack) > 1:
            stack[-2].remove(elem)
            elem.clear()
        elif (elem.tag == GRAPHML_TAG + "data" and len(stack) > 1 and
              stack[-2].tag in (GRAPHML_TAG + "node", GRAPHML_TAG + "edge")):
            stack.pop()
            continue
        stack.pop()

    if not graph.number_of_nodes() or not graph.number_of_edges():
        raise ValueError("GraphML contains no usable road nodes or edges")
    return graph


# ── Tile Index ───────────────────────────────────────────────────

def get_tile_id(row: int, col: int) -> str:
    return f"tile_{row:02d}_{col:02d}"


def tile_bbox(row: int, col: int) -> Dict:
    """Return (lat_min, lat_max, lon_min, lon_max) for tile (row, col) WITHOUT overlap."""
    lat_total = NAGPUR_BBOX["lat_max"] - NAGPUR_BBOX["lat_min"]
    lon_total = NAGPUR_BBOX["lon_max"] - NAGPUR_BBOX["lon_min"]
    lat_step  = lat_total / GRID_ROWS
    lon_step  = lon_total / GRID_COLS
    return {
        "lat_min": NAGPUR_BBOX["lat_min"] + row * lat_step,
        "lat_max": NAGPUR_BBOX["lat_min"] + (row + 1) * lat_step,
        "lon_min": NAGPUR_BBOX["lon_min"] + col * lon_step,
        "lon_max": NAGPUR_BBOX["lon_min"] + (col + 1) * lon_step,
    }


def tile_bbox_with_overlap(row: int, col: int) -> Dict:
    """Return bbox expanded by OVERLAP_DEG on each side (for tile download)."""
    bb = tile_bbox(row, col)
    return {
        "lat_min": max(NAGPUR_BBOX["lat_min"] - 0.01, bb["lat_min"] - OVERLAP_DEG),
        "lat_max": min(NAGPUR_BBOX["lat_max"] + 0.01, bb["lat_max"] + OVERLAP_DEG),
        "lon_min": max(NAGPUR_BBOX["lon_min"] - 0.01, bb["lon_min"] - OVERLAP_DEG),
        "lon_max": min(NAGPUR_BBOX["lon_max"] + 0.01, bb["lon_max"] + OVERLAP_DEG),
    }


def coord_to_tile(lat: float, lng: float) -> Tuple[int, int]:
    """Map a lat/lng to tile (row, col). Clamps to valid grid."""
    lat_total = NAGPUR_BBOX["lat_max"] - NAGPUR_BBOX["lat_min"]
    lon_total = NAGPUR_BBOX["lon_max"] - NAGPUR_BBOX["lon_min"]
    lat_step  = lat_total / GRID_ROWS
    lon_step  = lon_total / GRID_COLS
    row = int((lat - NAGPUR_BBOX["lat_min"]) / lat_step)
    col = int((lng - NAGPUR_BBOX["lon_min"]) / lon_step)
    row = max(0, min(GRID_ROWS - 1, row))
    col = max(0, min(GRID_COLS - 1, col))
    return row, col


def tiles_for_corridor(lat1, lng1, lat2, lng2, buffer=0) -> List[Tuple[int, int]]:
    """
    Return tiles intersecting the route corridor, optionally expanded by a
    tile-cell buffer. The default does not load unrelated neighboring tiles.
    """
    needed = set()
    samples = max(GRID_ROWS, GRID_COLS) * 4
    for i in range(samples + 1):
        t   = i / samples
        lat = lat1 + t * (lat2 - lat1)
        lng = lng1 + t * (lng2 - lng1)
        row, col = coord_to_tile(lat, lng)
        for dr in range(-buffer, buffer + 1):
            for dc in range(-buffer, buffer + 1):
                r2 = row + dr
                c2 = col + dc
                if 0 <= r2 < GRID_ROWS and 0 <= c2 < GRID_COLS:
                    needed.add((r2, c2))
    return sorted(needed)


def _route_tile_sets(lat1, lng1, lat2, lng2):
    """Return progressively expanded corridor sets, capped to control memory."""
    core = tiles_for_corridor(lat1, lng1, lat2, lng2)
    candidates = set(tiles_for_corridor(lat1, lng1, lat2, lng2, buffer=1)) - set(core)
    dx, dy = lng2 - lng1, lat2 - lat1
    denominator = dx * dx + dy * dy

    def distance_from_corridor(tile):
        bounds = tile_bbox(*tile)
        lat = (bounds["lat_min"] + bounds["lat_max"]) / 2
        lng = (bounds["lon_min"] + bounds["lon_max"]) / 2
        fraction = 0 if denominator == 0 else max(
            0, min(1, ((lng - lng1) * dx + (lat - lat1) * dy) / denominator))
        closest_lat = lat1 + fraction * dy
        closest_lng = lng1 + fraction * dx
        return (lat - closest_lat) ** 2 + (lng - closest_lng) ** 2

    ordered = sorted(candidates, key=distance_from_corridor)
    attempts = [list(core)]
    expansion_count = min(len(ordered), MAX_ROUTE_TILES - len(core))
    if expansion_count:
        attempts.append(sorted(core + ordered[:expansion_count]))
    return attempts


def tile_graphml_path(row: int, col: int) -> str:
    return os.path.join(TILES_DIR, f"{get_tile_id(row, col)}.graphml")


def required_tile_paths() -> Dict[str, str]:
    """Return the expected full-Nagpur tile set keyed by tile id."""
    return {
        get_tile_id(row, col): tile_graphml_path(row, col)
        for row in range(GRID_ROWS)
        for col in range(GRID_COLS)
    }


@lru_cache(maxsize=GRID_ROWS * GRID_COLS)
def _inspect_tile_file(path, size, modified_ns):
    """Stream-validate one GraphML file without constructing a road graph."""
    del size, modified_ns
    node_ids = set()
    unresolved_endpoints = set()
    key_names = {}
    node_count = 0
    edge_count = 0
    graph_count = 0
    stack = []
    try:
        for event, elem in ET.iterparse(path, events=("start", "end")):
            if event == "start":
                if elem.tag == GRAPHML_TAG + "graph":
                    graph_count += 1
                stack.append(elem)
                continue
            if elem.tag == GRAPHML_TAG + "key":
                key_names[elem.attrib.get("id")] = elem.attrib.get("attr.name")
            elif elem.tag == GRAPHML_TAG + "node":
                node_id = elem.attrib.get("id")
                if not node_id:
                    return False, node_count, edge_count, "node without id"
                if node_id in node_ids:
                    return False, node_count, edge_count, "duplicate node id"
                coordinates = {
                    key_names.get(data.attrib.get("key")): data.text
                    for data in elem.findall(GRAPHML_TAG + "data")
                }
                try:
                    lat = float(coordinates["y"])
                    lng = float(coordinates["x"])
                    if not math.isfinite(lat) or not math.isfinite(lng):
                        raise ValueError("non-finite coordinates")
                except (KeyError, TypeError, ValueError):
                    return False, node_count, edge_count, "node missing numeric x/y coordinates"
                node_ids.add(node_id)
                unresolved_endpoints.discard(node_id)
                node_count += 1
            elif elem.tag == GRAPHML_TAG + "edge":
                source = elem.attrib.get("source")
                target = elem.attrib.get("target")
                if not source or not target:
                    return False, node_count, edge_count, "edge without endpoints"
                if source not in node_ids:
                    unresolved_endpoints.add(source)
                if target not in node_ids:
                    unresolved_endpoints.add(target)
                edge_count += 1
            elif (elem.tag == GRAPHML_TAG + "data" and len(stack) > 1 and
                  stack[-2].tag in (GRAPHML_TAG + "node", GRAPHML_TAG + "edge")):
                stack.pop()
                continue
            if len(stack) > 1:
                stack[-2].remove(elem)
            elem.clear()
            stack.pop()
        if graph_count != 1:
            return False, node_count, edge_count, "expected exactly one graph"
        if not node_count or not edge_count:
            return False, node_count, edge_count, "graph has no nodes or edges"
        if unresolved_endpoints:
            return False, node_count, edge_count, "edge references missing nodes"
        return True, node_count, edge_count, None
    except (ET.ParseError, OSError, ValueError) as error:
        error_text = "unreadable GraphML" if isinstance(error, OSError) else str(error)
        return False, node_count, edge_count, error_text


def validate_tile_file(path):
    """Return file validity and graph counts; cache by immutable file metadata."""
    try:
        stat = os.stat(path)
    except OSError as error:
        return {"valid": False, "nodes": 0, "edges": 0, "error": "missing or unreadable file"}
    if not os.path.isfile(path) or stat.st_size == 0:
        return {"valid": False, "nodes": 0, "edges": 0, "error": "missing or empty file"}
    valid, nodes, edges, error = _inspect_tile_file(
        os.path.abspath(path), stat.st_size, stat.st_mtime_ns)
    return {"valid": valid, "nodes": nodes, "edges": edges, "error": error}


def tile_validation_status():
    """Validate all required tiles and return readiness counts and diagnostics."""
    tiles = {
        tile_id: validate_tile_file(path)
        for tile_id, path in required_tile_paths().items()
    }
    valid_count = sum(1 for tile in tiles.values() if tile["valid"])
    return {
        "tiles": tiles,
        "valid_tiles": valid_count,
        "invalid_tiles": len(tiles) - valid_count,
        "routing_ready": valid_count == len(tiles),
    }


def missing_tile_ids() -> List[str]:
    """Return every tile that cannot provide a usable graph."""
    return [tile_id for tile_id, path in required_tile_paths().items()
            if not validate_tile_file(path)["valid"]]


def tiles_available() -> bool:
    """Whether the complete full-Nagpur tile grid is ready for routing.

    A partial grid must not be reported as ready: routes crossing a missing
    tile would otherwise fail after health had claimed routing was available.
    """
    return os.path.isdir(TILES_DIR) and not missing_tile_ids()


# ── LRU Tile Cache ───────────────────────────────────────────────

class TileCache:
    """
    Thread-safe, one-tile LRU used only while composing a route graph.
    The route graph itself is never retained after the request completes.
    """

    def __init__(self, max_tiles: int = MAX_TILES):
        self._max   = max_tiles
        self._cache: OrderedDict[str, nx.MultiDiGraph] = OrderedDict()
        self._lock  = threading.Lock()
        self._load_lock = threading.Lock()
        self._blackspots = None   # shared across all tiles

    def _ensure_blackspots(self):
        if self._blackspots is None:
            self._blackspots = _load_blackspot_tree(DATASET_PATH)
        return self._blackspots

    def _load_tile(self, row: int, col: int) -> Optional[nx.MultiDiGraph]:
        path = tile_graphml_path(row, col)
        validation = validate_tile_file(path)
        if not validation["valid"]:
            raise ValueError(f"Unusable routing tile {get_tile_id(row, col)}: {validation['error']}")
        t0 = time.time()
        G = _load_route_graphml(path)
        if G.number_of_nodes() != validation["nodes"] or G.number_of_edges() != validation["edges"]:
            raise ValueError(
                f"GraphML loader count mismatch for {get_tile_id(row, col)}: "
                f"expected {validation['nodes']} nodes/{validation['edges']} edges, "
                f"loaded {G.number_of_nodes()} nodes/{G.number_of_edges()} edges"
            )
        bs = self._ensure_blackspots()
        _annotate_edges(G, bs)
        log.info("[TILE] Loaded tile_%02d_%02d  nodes=%d  edges=%d  t=%.1fs",
                 row, col, G.number_of_nodes(), G.number_of_edges(), time.time() - t0)
        return G

    def get(self, row: int, col: int) -> Optional[nx.MultiDiGraph]:
        key = get_tile_id(row, col)
        with self._lock:
            if key in self._cache:
                self._cache.move_to_end(key)  # mark as recently used
                return self._cache[key]
        with self._load_lock:
            with self._lock:
                if key in self._cache:
                    self._cache.move_to_end(key)
                    return self._cache[key]
            G = self._load_tile(row, col)
            with self._lock:
                self._cache[key] = G
                self._cache.move_to_end(key)
                while len(self._cache) > self._max:
                    evicted_key, _ = self._cache.popitem(last=False)
                    log.info("[TILE] Evicted %s from cache (LRU)", evicted_key)
            return G

    def clear(self):
        """Release all cached tile graphs after a route has been assembled."""
        with self._lock:
            self._cache.clear()

    def get_tiles_for_route(self, lat1, lng1, lat2, lng2, buffer=0,
                            tile_ids=None) -> nx.MultiDiGraph:
        """
        Load and compose all tiles needed for this route into a single graph.
        Raises when a required tile cannot provide a usable graph.
        """
        tile_ids = (tiles_for_corridor(lat1, lng1, lat2, lng2, buffer=buffer)
                    if tile_ids is None else sorted(set(tile_ids)))
        if len(tile_ids) > MAX_ROUTE_TILES:
            raise ValueError(
                f"Route corridor requires {len(tile_ids)} tiles; "
                f"limit is {MAX_ROUTE_TILES} to protect service memory."
            )
        log.info("[TILE] Loading %d selected route tiles: %s",
                 len(tile_ids), [get_tile_id(r, c) for r, c in tile_ids])

        if not tile_ids:
            raise ValueError("Route corridor did not intersect any routing tiles.")

        started = time.time()
        combined = None
        try:
            for row, col in tile_ids:
                tile = self.get(row, col)
                if combined is None:
                    combined = tile
                else:
                    # NetworkX update merges adjacency in place; compose_all
                    # would duplicate every accumulated node and edge.
                    combined.update(tile)
                del tile

            if combined is None or not combined.number_of_nodes() or not combined.number_of_edges():
                raise ValueError("Route corridor tiles contain no usable road graph.")
            log.info("[TILE] Composed %d tiles → %d nodes %d edges  t=%.2fs",
                     len(tile_ids), combined.number_of_nodes(), combined.number_of_edges(),
                     time.time() - started)
            return combined
        finally:
            self.clear()

    def cache_info(self):
        with self._lock:
            return {k: {"nodes": G.number_of_nodes(), "edges": G.number_of_edges()}
                    for k, G in self._cache.items()}


# Singleton cache instance
_tile_cache: Optional[TileCache] = None
_cache_lock = threading.Lock()


def get_tile_cache() -> TileCache:
    global _tile_cache
    if _tile_cache is None:
        with _cache_lock:
            if _tile_cache is None:
                _tile_cache = TileCache(max_tiles=MAX_TILES)
    return _tile_cache


# ── Nearest-Node lookup ──────────────────────────────────────────

def _nearest_node(G, lat, lng):
    best_node, best_dist = None, float("inf")
    for node, data in G.nodes(data=True):
        try:
            d = _haversine_m(lat, lng,
                             float(data.get("y", 0)),
                             float(data.get("x", 0)))
            if d < best_dist:
                best_dist, best_node = d, node
        except (ValueError, TypeError):
            continue
    return best_node


# ── A* Heuristic ─────────────────────────────────────────────────

def _astar_heuristic(G):
    def h(u, target):
        ui = G.nodes[u]
        ti = G.nodes[target]
        return _haversine_m(float(ui.get("y", 0)), float(ui.get("x", 0)),
                            float(ti.get("y", 0)), float(ti.get("x", 0)))
    return h


# ── Live Conditions ──────────────────────────────────────────────

def _live_conditions(conditions):
    conditions = conditions or {}
    traffic = conditions.get("traffic") or {}
    weather = conditions.get("weather") or {}
    try:
        current_speed = float(traffic.get("currentSpeed", 0))
        free_speed    = float(traffic.get("freeFlowSpeed", 0))
    except (TypeError, ValueError):
        current_speed = free_speed = 0.0
    congestion    = (max(0.0, min(1.0, 1.0 - current_speed / free_speed))
                     if free_speed > 0 and current_speed > 0 else 0.0)
    condition     = str(weather.get("condition") or weather.get("weather") or "CLEAR").upper()
    weather_risk  = WEATHER_RISK.get(condition, 0.20)
    return congestion, weather_risk


# ── Route Computation ────────────────────────────────────────────

def _compute_route(G, origin_lat, origin_lng, dest_lat, dest_lng,
                   risk_penalty=RISK_PENALTY, live_conditions=None):
    """Core A* routing on a composed graph G."""
    try:
        origin_node = _nearest_node(G, origin_lat, origin_lng)
        dest_node   = _nearest_node(G, dest_lat, dest_lng)
        if origin_node is None or dest_node is None:
            return {"success": False, "error": "Could not snap coordinates to graph nodes."}
        if origin_node == dest_node:
            return {"success": False, "error": "Origin and destination snap to the same node."}

        heuristic            = _astar_heuristic(G)
        congestion, wx_risk  = _live_conditions(live_conditions)

        def weight_fn(u, v, edge_dict):
            min_w = float("inf")
            for key, data in edge_dict.items():
                length    = float(data.get("length", 50.0))
                base_risk = float(data.get("risk_score", 0.35))
                dyn_risk  = min(1.0, base_risk + 0.25 * wx_risk + 0.20 * congestion)
                w         = length * (1.0 + 1.5 * congestion) + dyn_risk * risk_penalty
                min_w     = min(min_w, w)
            return min_w

        path_nodes = nx.astar_path(G, source=origin_node, target=dest_node,
                                   heuristic=heuristic, weight=weight_fn)

        route_coords = []
        for n in path_nodes:
            nd = G.nodes[n]
            route_coords.append([round(float(nd.get("y", 0)), 6),
                                  round(float(nd.get("x", 0)), 6)])

        total_dist_m, edge_risks = 0.0, []
        for i in range(len(path_nodes) - 1):
            u, v = path_nodes[i], path_nodes[i + 1]
            best_data, best_w = None, float("inf")
            for key, data in G[u][v].items():
                length    = float(data.get("length", 50.0))
                base_risk = float(data.get("risk_score", 0.35))
                dyn_risk  = min(1.0, base_risk + 0.25 * wx_risk + 0.20 * congestion)
                w         = length * (1.0 + 1.5 * congestion) + dyn_risk * risk_penalty
                if w < best_w:
                    best_w, best_data = w, data
            if best_data:
                total_dist_m += float(best_data.get("length", 0))
                edge_risks.append(
                    min(1.0, float(best_data.get("risk_score", 0.35)) +
                        0.25 * wx_risk + 0.20 * congestion))

        avg_risk = float(np.mean(edge_risks)) if edge_risks else 0.0
        max_risk = float(np.max(edge_risks))  if edge_risks else 0.0

        return {
            "success":           True,
            "route_nodes":       [str(n) for n in path_nodes],
            "route_coords":      route_coords,
            "total_distance_m":  round(total_dist_m, 1),
            "total_distance_km": round(total_dist_m / 1000.0, 3),
            "avg_risk_score":    round(avg_risk, 4),
            "max_risk_score":    round(max_risk, 4),
            "risk_level":        ("High" if avg_risk >= 0.55 else "Medium" if avg_risk >= 0.25 else "Low"),
            "num_waypoints":     len(path_nodes),
            "origin_node":       str(origin_node),
            "dest_node":         str(dest_node),
            "live_conditions":   {"congestion": round(congestion, 3),
                                  "weather_risk": round(wx_risk, 3)},
        }

    except nx.NetworkXNoPath:
        return {"success": False, "error": "No path found between origin and destination."}
    except nx.NodeNotFound as e:
        return {"success": False, "error": f"Node not found: {e}"}
    except Exception as e:
        log.exception("Tile routing error")
        return {"success": False, "error": str(e)}


def compare_routes_tile(origin_lat, origin_lng, dest_lat, dest_lng,
                        live_conditions=None):
    """
    Public entry point: load required tiles, compute safe and fast routes,
    return comparison dict compatible with the existing /safe-route API.
    """
    cache = get_tile_cache()
    safe = shortest = None
    for tile_ids in _route_tile_sets(origin_lat, origin_lng, dest_lat, dest_lng):
        G = cache.get_tiles_for_route(
            origin_lat, origin_lng, dest_lat, dest_lng, tile_ids=tile_ids)
        try:
            safe = _compute_route(G, origin_lat, origin_lng, dest_lat, dest_lng,
                                  risk_penalty=RISK_PENALTY, live_conditions=live_conditions)
            shortest = _compute_route(G, origin_lat, origin_lng, dest_lat, dest_lng,
                                      risk_penalty=0, live_conditions=live_conditions)
        finally:
            del G
            cache.clear()
        if safe.get("success") and shortest.get("success"):
            break

    comparison = {}
    if safe.get("success") and shortest.get("success"):
        extra_m   = safe["total_distance_m"] - shortest["total_distance_m"]
        risk_cut  = shortest["avg_risk_score"] - safe["avg_risk_score"]
        comparison = {
            "extra_distance_m":   round(extra_m, 1),
            "extra_distance_km":  round(extra_m / 1000.0, 3),
            "risk_reduction":     round(risk_cut, 4),
            "risk_reduction_pct": round(risk_cut * 100, 1),
            "recommendation": (
                "Safe route recommended" if risk_cut > 0.05
                else "Routes are similar — shortest path is fine"
            ),
        }

    return {"safe_route": safe, "short_route": shortest, "comparison": comparison}
